#!/usr/bin/env python3
"""Synthesize original Arauna creature voices; verify the checked-in PCM assets."""
import argparse
import csv
import hashlib
import json
import math
import random
import struct
import unicodedata
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RATE = 11025
parser = argparse.ArgumentParser()
parser.add_argument("--write", action="store_true")
args = parser.parse_args()

def folded(text):
    return unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().lower()

def read_csv(path):
    with (ROOT / path).open(newline="") as f:
        return list(csv.DictReader(f))

def archetype(row, description):
    text = folded(row["full_name"] + " " + description)
    types = row["types"].lower()
    if any(word in text for word in ("sapo", "perereca", "frog", "toad")):
        return "amphibian"
    if "bug" in types:
        return "insect"
    if any(word in text for word in ("passaro", "ave ", "bird", "arara", "quero", "tucan", "beija", "papaga", "coruja", "owl")):
        return "avian"
    if any(word in text for word in ("cobra", "serpent", "boiuna", "sucuri", "snake")):
        return "serpent"
    if "ghost" in types:
        return "spectral"
    if "water" in types:
        return "aquatic"
    if any(word in text for word in ("guara", "caramel", "cao", "cachorro", "dog", "capivar", "macaco", "monkey", "tamand", "quati", "onca", "gato", "cat")):
        return "mammal"
    if any(word in text for word in ("lata", "metal", "plast", "concret", "garrafa", "steel", "ice")):
        return "resonant"
    return "beast"

def voice(dex, family, stage, kind, types):
    seed = int(hashlib.sha256(f"arauna-cry-v1:{family}".encode()).hexdigest()[:8], 16)
    rng = random.Random(seed + dex * 65537)
    register = {"avian": 780, "insect": 950, "amphibian": 100, "mammal": 190,
                "aquatic": 330, "serpent": 140, "spectral": 220, "resonant": 430, "beast": 160}[kind]
    base = (register + seed % max(20, register // 2)) * .84 ** stage
    legendary = 329 <= dex <= 348 or 376 <= dex <= 386
    duration = min(.68, .27 + (seed % 100) / 600 + stage * .045 + (.12 if legendary else 0))
    count = int(RATE * duration)
    phase = noise = 0.
    samples = []
    pulses = 2 + seed % 3
    for i in range(count):
        t = i / RATE
        progress = i / (count - 1)
        sweep = 1 + .20 * math.sin(math.tau * progress) - .28 * progress
        vibrato = 1 + .025 * math.sin(math.tau * (8 + seed % 9) * t)
        if kind == "avian":
            sweep += .35 * math.sin(math.tau * progress * (2 + seed % 3))
        if kind == "spectral":
            sweep += .14 * math.sin(math.tau * progress * 3.5)
        phase += math.tau * base * sweep * vibrato / RATE
        noise = .78 * noise + .22 * rng.uniform(-1, 1)
        if kind == "insect":
            tone = math.sin(phase) + .35 * math.sin(2*phase) + .2 * math.sin(3*phase)
        elif kind in ("mammal", "beast", "amphibian"):
            tone = math.sin(phase + 1.25 * math.sin(phase*.5)) + .33 * math.sin(2*phase) + .20 * noise
        elif kind == "serpent":
            tone = .30 * math.sin(phase) + 1.25 * noise
        elif kind == "resonant":
            tone = math.sin(phase) + .32 * math.sin(phase*1.414) + .20 * math.sin(phase*2.13)
        else:
            tone = math.sin(phase) + .20 * math.sin(phase*2.01) + .09 * noise
        articulation = .45 + .55 * math.sin(math.pi * progress * pulses)**2
        fade = min(1, t/.015, (duration-t)/.045)
        envelope = math.sin(math.pi*progress)**.55 * max(0, fade) * articulation
        if "fire" in types:
            tone += noise * .15
        if "electric" in types:
            tone += .1 * math.sin(phase*3.1)
        samples.append(tone * envelope)
    mean = sum(samples) / len(samples)
    samples = [sample - mean for sample in samples]
    peak = max(abs(sample) for sample in samples)
    pcm = [round(sample / peak * 22000) for sample in samples]
    for i in range(96):
        pcm[i] = round(pcm[i] * i / 96)
        pcm[-1-i] = round(pcm[-1-i] * i / 96)
    assert max(map(abs, pcm)) <= 32767 and pcm[0] == pcm[-1] == 0
    return struct.pack("<" + "h"*count, *pcm)

rows = read_csv("docs/arauna/ARAUNA_DEX_ENGINE_MAPPING.csv")
assert len(rows) == 386
parents = {int(row["target_dex"]): int(row["arauna_dex"])
           for row in read_csv("docs/arauna/ARAUNA_EVOLUTIONS.csv")
           if row["target_dex"].isdigit() and row["target_dex"] != row["arauna_dex"]}
descriptions = {int(row["arauna_dex"]): " ".join(row.values())
                for row in read_csv("docs/arauna/ARAUNA_DEX_TEXT.csv")}
manifest, hashes = [], set()
header = ["// Original synthesized Arauna cries. Generated by build_native_cries.py.",
          "// Waveforms and tone tables are const ROM data; no new RAM allocation.", ""]
for row in rows:
    dex = int(row["arauna_dex"])
    family, stage, seen = dex, 0, set()
    while family in parents and family not in seen:
        seen.add(family)
        family = parents[family]
        stage += 1
    kind = archetype(row, descriptions.get(dex, ""))
    pcm = voice(dex, family, stage, kind, row["types"])
    digest = hashlib.sha256(pcm).hexdigest()
    assert digest not in hashes, (dex, "duplicate cry")
    hashes.add(digest)
    relative = f"sound/direct_sound_samples/cries/arauna/{dex:03d}.wav"
    path = ROOT / relative
    if args.write:
        path.parent.mkdir(parents=True, exist_ok=True)
        with wave.open(str(path), "wb") as wav:
            wav.setnchannels(1)
            wav.setsampwidth(2)
            wav.setframerate(RATE)
            wav.writeframes(pcm)
    else:
        with wave.open(str(path), "rb") as wav:
            assert (wav.getnchannels(), wav.getsampwidth(), wav.getframerate()) == (1, 2, RATE)
            assert wav.readframes(wav.getnframes()) == pcm, relative
    manifest.append({"dex": dex, "name": row["engine_name"], "species": row["species_constant"],
                     "family": family, "stage": stage, "archetype": kind, "rate": RATE,
                     "samples": len(pcm)//2, "pcm_sha256": digest})
    header.append(f'static const u8 ALIGNED(4) sAraunaCry{dex:03d}[] = INCBIN_U8("sound/direct_sound_samples/cries/arauna/{dex:03d}.bin");')
for name, tone_type in (("sAraunaCryTones", "0x20"), ("sAraunaCryTonesReverse", "0x30")):
    header.extend(("", f"static const struct ToneData {name}[NUM_SPECIES] =", "{"))
    for row in rows:
        dex = int(row["arauna_dex"])
        header.append(f'    [{row["species_constant"]}] = {{ {tone_type}, 60, 0, 0, (struct WaveData *)sAraunaCry{dex:03d}, 255, 0, 255, 0 }},')
    header.append("};")
generated = {
    "src/data/arauna_cries.h": "\n".join(header) + "\n",
    "sound/arauna_cries.json": json.dumps({
        "provenance": "Original deterministic synthesis; no sampled recordings.",
        "format": "PCM16 mono 11025 Hz; compressed by the standard wav2agb cry rule.",
        "voices": manifest}, ensure_ascii=False, indent=2) + "\n",
}
for relative, content in generated.items():
    path = ROOT / relative
    if args.write:
        path.write_text(content)
    else:
        assert path.read_text() == content, f"Stale generated cry table: {relative}"
print("Native Arauna cries: PASS (386 unique voices, PCM and ROM tables reproducible)")
